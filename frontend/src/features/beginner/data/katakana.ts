export function getAllKatakanaCharacters(): KanaCharacter[] {
  return KATAKANA_GROUPS.flatMap((group) => group.characters);
}

export function getKatakanaById(id: string): KanaCharacter | undefined {
  return getAllKatakanaCharacters().find((c) => c.id === id);
}

export function getKatakanaByCharacter(char: string): KanaCharacter | undefined {
  return getAllKatakanaCharacters().find((c) => c.character === char);
}
