export function getAllHiraganaCharacters(): KanaCharacter[] {
  return HIRAGANA_GROUPS.flatMap((group) => group.characters);
}

export function getHiraganaById(id: string): KanaCharacter | undefined {
  return getAllHiraganaCharacters().find((c) => c.id === id);
}

export function getHiraganaByCharacter(char: string): KanaCharacter | undefined {
  return getAllHiraganaCharacters().find((c) => c.character === char);
}
